#!/usr/bin/env python3
"""Embeds the native replacement shaders into the Switch build.

Reads the <hash>_ps_<modification>.spv modules build_native_shaders.py writes
and emits a C++ table the native renderer looks them up in (by ucode hash and
translator modification), so the NRO needs no native_shaders folder.

usage: embed_native_shaders.py <spv_dir> <out.cpp>
"""
import os
import sys


def main():
    spv_dir, out_path = sys.argv[1], sys.argv[2]
    entries = []
    for name in sorted(os.listdir(spv_dir)):
        base, ext = os.path.splitext(name)
        if ext != ".spv":
            continue
        shader_hash, stage, modification = base.split("_")
        if stage != "ps":
            continue
        data = open(os.path.join(spv_dir, name), "rb").read()
        entries.append((shader_hash, modification, data))
    lines = [
        "// Generated by simpsons/cmake/embed_native_shaders.py from",
        "// tools/native-renderer/native_shaders. Do not edit.",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace simpsons::native {",
        "",
        "struct EmbeddedShader {",
        "  uint64_t ucode_hash;",
        "  uint64_t modification;",
        "  const uint32_t* words;",
        "  size_t word_count;",
        "};",
        "",
    ]
    for i, (_, _, data) in enumerate(entries):
        words = [int.from_bytes(data[j:j + 4], "little") for j in range(0, len(data), 4)]
        lines.append(f"static const uint32_t kShader{i}[] = {{")
        for j in range(0, len(words), 8):
            lines.append("  " + ", ".join(f"0x{w:08X}u" for w in words[j:j + 8]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("extern const EmbeddedShader kEmbeddedPixelShaders[] = {")
    for i, (shader_hash, modification, data) in enumerate(entries):
        lines.append(f"  {{0x{shader_hash}ull, 0x{modification}ull, kShader{i}, {len(data) // 4}}},")
    lines.append("};")
    lines.append(f"extern const size_t kEmbeddedPixelShaderCount = {len(entries)};")
    lines.append("")
    lines.append("}  // namespace simpsons::native")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
