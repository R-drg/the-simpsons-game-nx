#!/usr/bin/env python3
"""Assemble NOTICE from the licence files of everything that reaches the user.

    tools/make_notice.py --sdk /path/to/rexglue-sdk > NOTICE

The table below is a judgement about what is in the shipped link line, not a
tree walk. `disasm` is absent on purpose: it is GPL binutils, part of the
recompiler toolchain, and never linked into a shipped binary.
"""

import argparse
import pathlib
import sys
import textwrap

# name, licence, path under the SDK's thirdparty/, optional note
# SDL3, Snappy, Tracy and volk are left out: the Switch build compiles none
# of them (Tracy is off, Vulkan is linked statically from Mesa).
